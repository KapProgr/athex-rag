Q = []


def num(id, company, year, question, value, answer, evidence, source="text"):
    Q.append(
        dict(
            id=id,
            company=company,
            year=year,
            question=question,
            type="numeric",
            source=source,
            answer=answer,
            answer_value=value,
            evidence=evidence,
        )
    )


def txt(id, company, year, question, answer, evidence, alternatives=(), source="text"):
    Q.append(
        dict(
            id=id,
            company=company,
            year=year,
            question=question,
            type="text",
            source=source,
            answer=answer,
            alternatives=list(alternatives),
            evidence=evidence,
        )
    )


def none(id, company, year, question, forbidden):
    Q.append(
        dict(
            id=id,
            company=company,
            year=year,
            question=question,
            type="unanswerable",
            evidence=forbidden,
        )
    )


